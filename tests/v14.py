import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(args=["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"])
        pg=await b.new_page(viewport={"width":390,"height":844},device_scale_factor=2)
        errs=[];pg.on("pageerror",lambda e:errs.append("PAGEERR "+str(e)[:300]))
        pg.on("console",lambda m:errs.append("console:"+m.text[:250]) if m.type=="error" and "Failed to load resource" not in m.text and "AudioContext" not in m.text else None)
        await pg.goto("http://127.0.0.1:8765/csp.html")
        await pg.evaluate("localStorage.clear();localStorage.setItem('fho_legalV','1')");await pg.reload()
        await pg.wait_for_timeout(3000)
        print("onb:",await pg.evaluate("!!document.querySelector('#onbModal')"))
        await pg.click("#onbModal .btn:not(.ghost) >> nth=-1")
        await pg.wait_for_timeout(500)
        if await pg.evaluate("!!document.querySelector('#onbModal')"):
            await pg.evaluate("[...document.querySelectorAll('#onbModal button')].find(b=>/skip|later/i.test(b.textContent))?.click()")
        await pg.wait_for_timeout(3500)
        print("tour:",await pg.evaluate("!!document.querySelector('#tourOv')"))
        await pg.screenshot(path="t14_tour0.png")
        for i in range(3):
            await pg.click("#tourTip .btn:not(.ghost)");await pg.wait_for_timeout(500)
        await pg.screenshot(path="t14_tour3.png")
        n=await pg.evaluate("TR.steps.length");print("steps",n)
        for i in range(n-3):
            await pg.evaluate("document.querySelector('#tourTip .btn:not(.ghost)').click()");await pg.wait_for_timeout(350)
            if i==n-6: await pg.screenshot(path="t14_tourTab.png")
        print("tour closed:",not await pg.evaluate("!!document.querySelector('#tourOv')"),"toured",await pg.evaluate("localStorage.getItem('fho_toured')"))
        await pg.wait_for_timeout(500)
        await pg.click("#helpChip");await pg.wait_for_timeout(500)
        await pg.screenshot(path="t14_help.png")
        await pg.evaluate("document.querySelector('.hp-guide summary').click()");await pg.wait_for_timeout(200)
        await pg.screenshot(path="t14_help2.png",full_page=False)
        await pg.evaluate("[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Settings ▶')).click()");await pg.wait_for_timeout(800)
        await pg.screenshot(path="t14_settings.png")
        print("tab label:",await pg.evaluate("document.querySelector('.tabs [data-v=\"me\"]').textContent"))
        print("hint:",await pg.evaluate("document.querySelector('#view-me .tab-hint')?.textContent?.slice(0,60)"))
        print("chrome opt:",await pg.evaluate("(o=>o&&[o.disabled,o.textContent])(document.querySelector('#brainKind option[value=chrome]'))"),"pvChrome",await pg.evaluate("!!document.querySelector('#pvChrome')"))
        await pg.evaluate("[...document.querySelectorAll('.set-grid .ac-tile')][1].click()");await pg.wait_for_timeout(900)
        await pg.screenshot(path="t14_jump.png")
        await pg.evaluate("switchTab('today')");await pg.wait_for_timeout(700)
        print("tipcard:",await pg.evaluate("!!document.querySelector('.hp-tipcard')"))
        await pg.screenshot(path="t14_today.png")
        await pg.evaluate("switchTab('learn')");await pg.wait_for_timeout(500)
        print("learn hint:",await pg.evaluate("!!document.querySelector('#view-learn .tab-hint')"))
        print("\n".join(errs[:15]) or "no errors")
        await b.close()
asyncio.run(main())
