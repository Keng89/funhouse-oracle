import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(args=["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"])
        pg=await b.new_page(viewport={"width":390,"height":844},device_scale_factor=2)
        errs=[];pg.on("pageerror",lambda e:errs.append("PAGEERR "+str(e)[:300]))
        pg.on("console",lambda m:errs.append("console:"+m.text[:250]) if m.type=="error" and "Failed to load resource" not in m.text and "AudioContext" not in m.text else None)
        dl=[];pg.on("dialog",lambda d:asyncio.ensure_future(d.accept("DELETE") if d.type=="prompt" else d.accept()))
        await pg.goto("http://127.0.0.1:8765/csp.html");await pg.evaluate("localStorage.clear()");await pg.reload();await pg.wait_for_timeout(3000)
        print("consent:",await pg.evaluate("!!$('#consentModal')"),"btn disabled",await pg.evaluate("$('#consentModal .btn').disabled"))
        await pg.screenshot(path="t17_consent.png")
        await pg.evaluate("[...document.querySelectorAll('#consentModal a')][0].click()");await pg.wait_for_timeout(400)
        await pg.screenshot(path="t17_terms.png")
        await pg.evaluate("document.querySelector('.lg-modal').remove()")
        await pg.click("#csAge");await pg.click("#csAgree");await pg.click("#consentModal .btn:not(.cs-kid)");await pg.wait_for_timeout(300)
        print("consented:",await pg.evaluate("[!$('#consentModal'),localStorage.getItem('fho_legalV')]"))
        await pg.wait_for_timeout(1500)
        # finish onboarding & tour quickly
        await pg.evaluate("document.querySelectorAll('#onbModal').forEach(m=>m.remove());localStorage.setItem('fho_onb2','true');localStorage.setItem('fho_toured','true');endTour&&endTour()")
        await pg.wait_for_timeout(500)
        print("ai note:",await pg.evaluate("$('#aiNote')?.textContent?.slice(0,40)"),"stage label:",await pg.evaluate("getComputedStyle($('#stageName'),'::after').content"))
        print("sys has safety:",await pg.evaluate("sysPrompt().includes('Safety rules')"))
        await pg.fill("#input","I want to die");await pg.click("#sendBtn");await pg.wait_for_timeout(800)
        print("crisis card:",await pg.evaluate("!!document.querySelector('#chat .crisis-card')"),await pg.evaluate("localStorage.getItem('fho_crisisN')"))
        await pg.screenshot(path="t17_crisis.png")
        await pg.fill("#input","tell me a joke");await pg.click("#sendBtn");await pg.wait_for_timeout(1500)
        print("normal reply count:",await pg.evaluate("document.querySelectorAll('#chat .crisis-card').length"))
        await pg.evaluate("switchTab('me')");await pg.wait_for_timeout(300)
        print("legal tile+foot:",await pg.evaluate("[!!$('#legalFoot'),[...document.querySelectorAll('.set-grid b')].map(b=>b.textContent)]"))
        await pg.evaluate("$('#legalFoot').scrollIntoView()");await pg.wait_for_timeout(200);await pg.screenshot(path="t17_foot.png")
        await pg.evaluate("openLegal('privacy')");await pg.wait_for_timeout(300);await pg.screenshot(path="t17_privacy.png")
        await pg.evaluate("document.querySelectorAll('.hb-modal').forEach(m=>m.remove())")
        # kids mic
        await pg.evaluate("KIDS.pin=pinHash('1234');KIDS.list=[{id:'k1',name:'Max',em:'🐯',age:'6-8',lim:0}];saveKIDS();enterKid('k1')");await pg.wait_for_timeout(800)
        print("kid nomic:",await pg.evaluate("[document.body.classList.contains('nomic'),sysPrompt().includes('young child')]"))
        await pg.evaluate("switchTab('chat')");await pg.fill("#input","i want to hurt myself");await pg.click("#sendBtn");await pg.wait_for_timeout(600)
        print("kid crisis:",await pg.evaluate("[...document.querySelectorAll('#chat .msg.bot .bubble')].pop().textContent.slice(0,60)"))
        await pg.screenshot(path="t17_kidcrisis.png")
        # delete all
        await pg.evaluate("deleteAll()");await pg.wait_for_timeout(5000)
        print("after delete keys:",await pg.evaluate("Object.keys(localStorage).filter(k=>k.startsWith('fho_')).length"),"consent shown again:",await pg.evaluate("!!document.querySelector('#consentModal')"))
        print("\n".join(errs[:15]) or "no errors")
        await b.close()
asyncio.run(main())
